// Records the save format of the current GW.SAVE_SCHEMA: the shape fingerprint
// (tests/save-shapes/schema-N.json) and a fixture save (tests/fixtures/save-schema-N.json),
// both taken from the representative game in tests/save-support.mjs.
//
//   npm run save:snapshot            write whichever of the two is missing
//   npm run save:snapshot -- --force overwrite them (only while schema N is unreleased)
//
// Run it once after bumping GW.SAVE_SCHEMA. Never rerun it to make a failing fingerprint
// test pass for a schema that players already have saves in: bump the schema instead.
import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from '../tests/harness.mjs';
import { representativeGame, fingerprint, shapeFile, fixtureFile, SHAPES_DIR, FIXTURES_DIR } from '../tests/save-support.mjs';

const force = process.argv.includes('--force');
const G = representativeGame();
const schema = G.SAVE_SCHEMA, save = G.Save.serialize();
G.Save.validate(save);

const outputs = [
  [shapeFile(schema), { schema, note: 'Generated by tools/save-snapshot.mjs. Do not edit by hand; see "Changing the save format" in docs/ARCHITECTURE.md.', shape: fingerprint(save) }],
  [fixtureFile(schema), save]
];
fs.mkdirSync(SHAPES_DIR, { recursive: true });
fs.mkdirSync(FIXTURES_DIR, { recursive: true });
let wrote = 0;
for (const [file, data] of outputs){
  const rel = path.relative(ROOT, file);
  if (fs.existsSync(file) && !force){ console.log(`kept    ${rel} (exists; --force overwrites)`); continue; }
  fs.writeFileSync(file, JSON.stringify(data, null, file.includes('save-shapes') ? 1 : 0) + '\n');
  console.log(`wrote   ${rel}`);
  wrote++;
}
console.log(wrote ? `Recorded save schema ${schema}.` : `Save schema ${schema} was already recorded.`);
